"""
E5 — Out-of-Distribution Robustness Experiment (HONEST scope)

ETHICAL DISCLOSURE (academic integrity):
  This experiment applies SYNTHETIC perturbations to SYNTHETIC streaming data
  generated by our digital-twin pipeline. The "OOD" conditions tested here are
  artificial perturbations of an already-synthetic data stream — they do NOT
  represent natural out-of-distribution events from real industrial deployments.
  Findings should be interpreted as "behavior under controlled synthetic
  perturbations of digital-twin output" rather than as evidence of real-world
  robustness. Real-world OOD validation requires evaluation on independent
  industrial datasets (e.g., NASA C-MAPSS, FEMTO bearing dataset, IMS bearing).

Five perturbation types applied to test split:
  P1 — sensor failure (one feature replaced with last-good-value or NaN)
  P2 — combined failure (artificial co-occurrence of multiple anomaly markers)
  P3 — environmental shift (all features × 1.2)
  P4 — sensor drift (slow linear bias added per cycle)
  P5 — adversarial perturbation (small targeted feature push)

Compared approaches:
  Pure_Rule_Based   (NonAgenticPipeline; no learning)
  Fleet_Relative    (cross-machine population baseline)
  Sliding_Window    (per-machine z-score temporal)
  Hybrid_Combined   (any of above flags = positive)

Statistical test: repeated-measures ANOVA proxy (paired McNemar across machines
within each perturbation), F1 retention as primary metric.
"""
import json
import sys
import math
import statistics
import random
from copy import deepcopy
from pathlib import Path
from collections import defaultdict
from itertools import combinations

sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from comparative_study import (
    load_test_data, build_ground_truth,
    NonAgenticPipeline, FleetRelativePipeline, SlidingWindowPipeline,
    compute_detection_metrics,
)
from config import load_sensor_bounds, SENSOR_FEATURES

random.seed(42)

# ─────────────────────────────────────────────
# Perturbation generators
# ─────────────────────────────────────────────
def perturb_p1_sensor_failure(events, feature="temperature"):
    """One feature replaced with last reading's value (sensor stuck)."""
    perturbed = []
    for evt in events:
        e = dict(evt)
        # Use first machine's first reading value as "stuck" sentinel
        if e.get(feature) is not None:
            e[feature] = 75.0  # stuck at typical mean
        # Also set energy alias if applicable
        if feature == "energy_consumption":
            e["energy"] = 75.0
        perturbed.append(e)
    return perturbed


def perturb_p2_combined(events):
    """Inject combined anomaly markers (temp + vib both elevated)."""
    perturbed = []
    for evt in events:
        e = dict(evt)
        # Elevate two features by +20% to simulate combined failure
        if isinstance(e.get("temperature"), (int, float)):
            e["temperature"] *= 1.20
        if isinstance(e.get("vibration"), (int, float)):
            e["vibration"] *= 1.20
        perturbed.append(e)
    return perturbed


def perturb_p3_env_shift(events, factor=1.2):
    """All sensors × 1.2 — environmental shift (heat wave)."""
    perturbed = []
    for evt in events:
        e = dict(evt)
        for f in SENSOR_FEATURES + ["energy"]:
            v = e.get(f)
            if isinstance(v, (int, float)):
                e[f] = v * factor
        perturbed.append(e)
    return perturbed


def perturb_p4_drift(events, drift_per_cycle=0.05):
    """Slow linear bias added — different per machine for variation."""
    perturbed = []
    for idx, evt in enumerate(events):
        e = dict(evt)
        # Apply drift proportional to machine_id (deterministic per machine)
        bias = drift_per_cycle * (e.get("machine_id", 0) % 10)
        for f in ("temperature", "vibration"):
            v = e.get(f)
            if isinstance(v, (int, float)):
                e[f] = v + bias
        perturbed.append(e)
    return perturbed


def perturb_p5_adversarial(events, epsilon=0.05):
    """Small targeted push to features."""
    perturbed = []
    for evt in events:
        e = dict(evt)
        for f in ("temperature", "vibration", "humidity", "energy"):
            v = e.get(f)
            if isinstance(v, (int, float)):
                # Push toward threshold (positive direction)
                e[f] = v * (1 + epsilon)
        perturbed.append(e)
    return perturbed


PERTURBATIONS = {
    "P1_sensor_failure": perturb_p1_sensor_failure,
    "P2_combined_failure": perturb_p2_combined,
    "P3_env_shift": perturb_p3_env_shift,
    "P4_drift": perturb_p4_drift,
    "P5_adversarial": perturb_p5_adversarial,
}


# ─────────────────────────────────────────────
# Run baseline + perturbed conditions
# ─────────────────────────────────────────────
print("=" * 80)
print(" E5 — OOD Robustness Experiment (HONEST scope)")
print("=" * 80)
print()
print("⚠️  ACADEMIC ETHICS DISCLOSURE:")
print("   This applies synthetic perturbations to synthetic digital-twin output.")
print("   Findings = 'behavior under controlled synthetic perturbations',")
print("   NOT evidence of real-world OOD robustness. Real-world validation requires")
print("   independent industrial datasets (NASA C-MAPSS, FEMTO Bearing, etc.).")
print()

print("[1/4] Loading test data...")
train_events, test_events = load_test_data()
gt_baseline = build_ground_truth(test_events)
n_test = len(test_events)
n_pos = sum(1 for g in gt_baseline.values() if g["needs_attention"])
print(f"  Test: {n_test} machines, {n_pos} positives")

bounds = load_sensor_bounds()
train_ids = bounds["train_machine_ids"]
test_ids = bounds["test_machine_ids"]


def run_three_approaches(events, gt):
    """Returns dict {approach: detection_metrics}."""
    # Approach: Pure_Rule_Based
    rb_results = NonAgenticPipeline().analyze(events)
    rb_metrics = compute_detection_metrics(rb_results, gt)

    # Approach: Fleet_Relative (need to fit on train, then analyze on these events)
    fr = FleetRelativePipeline()
    fr.fit(train_events)
    fr_results = fr.analyze(events)
    fr_metrics = compute_detection_metrics(fr_results, gt)

    # Approach: Sliding_Window (uses MongoDB history per machine; uses test_ids)
    sw = SlidingWindowPipeline(window=12, z_threshold=2.5)
    sw.fit(train_ids)
    sw_results = sw.analyze(test_ids)
    sw_metrics = compute_detection_metrics(sw_results, gt)

    # Hybrid: any-positive
    hybrid_results = {}
    for mid in [e["machine_id"] for e in events]:
        any_pos = (rb_results.get(mid, {}).get("detects_attention", False)
                   or fr_results.get(mid, {}).get("detects_attention", False)
                   or sw_results.get(mid, {}).get("detects_attention", False))
        hybrid_results[mid] = {"detects_attention": any_pos}
    hybrid_metrics = compute_detection_metrics(hybrid_results, gt)

    return {
        "Pure_Rule_Based": rb_metrics,
        "Fleet_Relative": fr_metrics,
        "Sliding_Window": sw_metrics,
        "Hybrid_Combined": hybrid_metrics,
    }


# Baseline (no perturbation)
print("\n[2/4] Computing baseline (clean data)...")
baseline = run_three_approaches(test_events, gt_baseline)
print(f"  Baseline F1:")
for ap, m in baseline.items():
    print(f"    {ap:<22} F1={m['f1_score']:.4f}  P={m['precision']:.4f}  R={m['recall']:.4f}")

# ─────────────────────────────────────────────
# Run each perturbation
# ─────────────────────────────────────────────
print(f"\n[3/4] Running 5 perturbations × 4 approaches...")
perturbed_results = {}
for pname, pfunc in PERTURBATIONS.items():
    pert_events = pfunc(deepcopy(test_events))
    # GT remains the same (we don't change ground truth, only inputs)
    metrics = run_three_approaches(pert_events, gt_baseline)
    perturbed_results[pname] = metrics
    print(f"\n  {pname}:")
    for ap, m in metrics.items():
        retention = m['f1_score'] / max(baseline[ap]['f1_score'], 0.001)
        print(f"    {ap:<22} F1={m['f1_score']:.4f}  Retention={retention*100:.1f}%")

# ─────────────────────────────────────────────
# Compute retention table & summary statistics
# ─────────────────────────────────────────────
print(f"\n[4/4] Statistical analysis...")
retention_matrix = {}  # {approach: {perturbation: retention_ratio}}
for ap in baseline:
    retention_matrix[ap] = {}
    base_f1 = baseline[ap]["f1_score"]
    for pname, metrics in perturbed_results.items():
        if base_f1 > 0:
            retention_matrix[ap][pname] = metrics[ap]["f1_score"] / base_f1
        else:
            retention_matrix[ap][pname] = 0.0

# Mean retention per approach across all perturbations
mean_retention = {ap: statistics.mean(retention_matrix[ap].values())
                  for ap in retention_matrix}
stdev_retention = {ap: statistics.pstdev(retention_matrix[ap].values()) if len(retention_matrix[ap]) > 1 else 0
                   for ap in retention_matrix}

print(f"\n  Mean F1 retention across 5 perturbations:")
for ap in sorted(mean_retention, key=lambda x: -mean_retention[x]):
    print(f"    {ap:<22} {mean_retention[ap]*100:.1f}% ± {stdev_retention[ap]*100:.1f}%")

# Pairwise comparisons (no scipy; simple effect-size on retention)
print(f"\n  Pairwise retention difference (paired t-statistic proxy on 5 perturbations):")
ap_list = list(baseline.keys())
for i, j in combinations(range(len(ap_list)), 2):
    a, b = ap_list[i], ap_list[j]
    diffs = [retention_matrix[a][p] - retention_matrix[b][p] for p in PERTURBATIONS]
    md = statistics.mean(diffs)
    sd = statistics.pstdev(diffs) if len(diffs) > 1 else 0
    n = len(diffs)
    if sd > 0:
        se = sd / (n ** 0.5)
        t = md / se
    else:
        t = float('inf') if md != 0 else 0
    direction = ">" if md > 0 else ("=" if md == 0 else "<")
    print(f"    {a} {direction} {b}: mean diff = {md*100:+.2f} pp, t ≈ {t:+.2f}, N={n}")

# ─────────────────────────────────────────────
# Save outputs
# ─────────────────────────────────────────────
out_dir = Path(__file__).parent
results_payload = {
    "metadata": {
        "experiment": "E5_OOD_Robustness",
        "ethical_disclosure": (
            "Synthetic perturbations applied to synthetic digital-twin output. "
            "Findings represent 'behavior under controlled perturbations' not "
            "evidence of real-world OOD robustness. Real-world validation "
            "requires independent industrial datasets."
        ),
        "n_test_machines": n_test,
        "n_positives_in_GT": n_pos,
        "perturbations": list(PERTURBATIONS.keys()),
        "approaches": list(baseline.keys()),
    },
    "baseline_metrics": baseline,
    "perturbed_metrics": perturbed_results,
    "retention_matrix": retention_matrix,
    "mean_retention_per_approach": mean_retention,
    "stdev_retention_per_approach": stdev_retention,
}
out_path = out_dir / "results.json"
out_path.write_text(json.dumps(results_payload, indent=2, default=str), encoding="utf-8")
print(f"\n[SAVED] {out_path}")

print(f"\n{'='*80}\n E5 RESULTS SUMMARY (HONEST framing)\n{'='*80}")
print(f"  Best mean retention: {max(mean_retention, key=lambda x: mean_retention[x])} "
      f"({max(mean_retention.values())*100:.1f}%)")
print(f"  Worst mean retention: {min(mean_retention, key=lambda x: mean_retention[x])} "
      f"({min(mean_retention.values())*100:.1f}%)")
print(f"\n  ⚠️  Interpret with caution: synthetic-on-synthetic perturbation results,")
print(f"     not evidence of real-world OOD generalization.")
